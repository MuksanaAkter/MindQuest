import { test, expect } from "@playwright/test";
import { config } from "dotenv";
import { Pool } from "pg";
import type { ArenaView } from "@mindquest/server/arena/contracts";
config({ path: "apps/web/.env", quiet: true });
// Isolate parallel test visitors from the production signup IP rate limit.
test.use({ extraHTTPHeaders: { "x-forwarded-for": "192.0.2.11" } });
test("only creators log in; a named avatar can join, finish, and appear in private creator results", async ({ page, browser, playwright }) => {
  test.skip(process.env.RUN_DB_E2E !== "1", "Needs a migrated local PostgreSQL database.");
  const pool = new Pool({ connectionString: process.env.DATABASE_URL });
  const participantContext = await browser.newContext(); const participant = await participantContext.newPage();
  const outsider = await playwright.request.newContext({ baseURL: "http://localhost:3000" });
  let creatorId: string | undefined; let otherCreatorId: string | undefined;
  try {
    await page.goto("/create"); await expect(page).toHaveURL(/\/login$/);
    expect((await outsider.post("/api/quizzes", { data: { title: "Unauthorized" } })).status()).toBe(401);
    const account = await page.request.post("/api/auth/sign-up/email", { data: { name: "Quiz Creator", email: `creator-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`, password: "Test-password-42!" }, headers: { Origin: "http://localhost:3000" } });
    creatorId = ((await account.json()) as { user: { id: string } }).user.id;
    await page.goto("/create");
    await page.getByLabel("Quiz title", { exact: true }).fill("Planet discovery quiz");
    await page.getByLabel("Question text", { exact: true }).fill("Which planet is known as the Red Planet?");
    for (const [i, option] of ["Mars", "Venus", "Earth", "Jupiter"].entries()) await page.getByLabel(`Option ${String.fromCharCode(65 + i)}`, { exact: true }).fill(option);
    await page.getByLabel("Explanation (optional)").fill("Iron-rich minerals give Mars its red appearance.");
    await page.getByRole("button", { name: "Publish quiz", exact: true }).click();
    await expect(page.locator(".quiz-code")).toBeVisible();
    const code = await page.locator(".quiz-code").innerText(); expect(code).toMatch(/^[A-Z2-9]{8}$/);
    const publicResponse = await outsider.get("/api/quizzes/public"); const publicText = await publicResponse.text();
    expect(publicText).not.toContain("correctIndex"); expect(publicText).not.toContain("options");
    await participant.goto(`http://localhost:3000/?code=${code}#join-quiz`);
    await participant.getByLabel("Your player name").fill("Ada Explorer");
    await participant.getByRole("button", { name: "fox avatar", exact: true }).click();
    await participant.getByRole("button", { name: "Join quiz", exact: true }).click();
    await expect(participant).toHaveURL(/\/play\//);
    await expect(participant.getByText("Ada Explorer · Participant")).toBeVisible();
    const id = new URL(participant.url()).pathname.split("/").at(-1)!;
    expect((await outsider.get(`/api/arena/${id}`)).status()).toBe(404);
    const before: ArenaView = await (await participant.request.get(`/api/arena/${id}`)).json();
    expect(before.question).not.toHaveProperty("snapshot"); expect(before.quiz?.avatar).toBe("fox");
    await participant.getByRole("button", { name: /^[ABCD] Mars$/ }).click();
    await participant.getByRole("button", { name: "Lock in answer", exact: true }).click();
    await expect(participant.getByRole("heading", { name: "A brilliant discovery!" })).toBeVisible();
    await participant.getByRole("button", { name: "Reveal my results", exact: true }).click();
    await expect(participant.getByText("1/1", { exact: true })).toBeVisible();
    await expect(participant.getByText("Ada Explorer · Your result is saved for the quiz creator.")).toBeVisible();
    await participant.reload(); await expect(participant.getByText("1/1", { exact: true })).toBeVisible();
    expect((await participant.request.get("/api/quizzes")).status()).toBe(401);
    await page.getByRole("button", { name: "Refresh results", exact: true }).click();
    await expect(page.getByText("Ada Explorer", { exact: true })).toBeVisible();
    await expect(page.getByText("100 pts", { exact: false })).toBeVisible();
    const creatorList = await (await page.request.get("/api/quizzes")).json() as { quizzes: { id: string }[] };
    const quizId = creatorList.quizzes[0].id;
    expect((await outsider.patch(`/api/quizzes/${quizId}`, { data: { published: false } })).status()).toBe(401);
    const creatorJoin = await page.request.post("/api/quizzes/join", { data: { code, name: "Creator Player", avatar: "dragon" } });
    const owned = (await creatorJoin.json()) as { attempt: ArenaView };
    expect((await page.request.get(`/api/arena/${owned.attempt.id}`)).status()).toBe(200);
    const selected = owned.attempt.question!.options.find((option) => option.text === "Mars")!;
    const answered: ArenaView = await (await page.request.post(`/api/arena/${owned.attempt.id}`, { data: { action: "answer", questionId: owned.attempt.question!.id, choiceId: selected.id } })).json();
    expect(answered.xpAwarded).toBe(0);
    const rewards = await pool.query<{ count: string }>('SELECT COUNT(*) FROM "GameReward" WHERE "userId" = $1', [creatorId]);
    expect(Number(rewards.rows[0].count)).toBe(0);
    const other = await outsider.post("/api/auth/sign-up/email", { data: { name: "Other Creator", email: `other-creator-${Date.now()}@example.com`, password: "Test-password-42!" }, headers: { Origin: "http://localhost:3000" } });
    otherCreatorId = ((await other.json()) as { user: { id: string } }).user.id;
    expect((await outsider.patch(`/api/quizzes/${quizId}`, { data: { published: false } })).status()).toBe(404);
    expect(await (await outsider.get("/api/quizzes")).json()).toEqual({ quizzes: [] });
    await page.getByRole("button", { name: "Close quiz", exact: true }).click();
    await expect(page.getByText("Closed to new participants")).toBeVisible();
    expect((await outsider.post("/api/quizzes/join", { data: { code, name: "New Player", avatar: "owl" } })).status()).toBe(404);
  } finally {
    await participantContext.close(); await outsider.dispose();
    if (otherCreatorId) await pool.query('DELETE FROM "User" WHERE id = $1', [otherCreatorId]);
    if (creatorId) await pool.query('DELETE FROM "User" WHERE id = $1', [creatorId]);
    await pool.end();
  }
});
